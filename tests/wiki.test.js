global.NL = require('../src/engine.js');
const W = require('../src/wiki.js');
let bad = 0; const ok = (c, m) => { console.log((c ? 'ok   ' : 'FAIL ') + m); if (!c) bad++; };
const all = W.all(), ids = all.map(a => a.id);
ok(new Set(ids).size === ids.length, 'Artikel-IDs eindeutig (' + ids.length + ' Artikel)');
const cats = new Set(W.CATS.map(c => c.id));
ok(all.every(a => cats.has(a.cat)), 'jeder Artikel hat eine gueltige Kategorie');
ok(W.CATS.every(c => W.byCat(c.id).length > 0), 'jede Kategorie hat Artikel');
const dead = []; all.forEach(a => { (a.body.match(/\[\[([^\]|]+)/g) || []).forEach(m => { const t = m.slice(2); if (!W.get(t)) dead.push(a.id + ' -> ' + t); }); (a.rel || []).forEach(r => { if (!W.get(r)) dead.push(a.id + ' rel -> ' + r); }); });
ok(!dead.length, 'alle Verweise gueltig' + (dead.length ? ': ' + dead.join(', ') : ''));
ok(Object.keys(NL.MODELS).every(k => W.get('hw-' + k.toLowerCase())), 'jedes Geraetemodell hat einen Artikel');
ok(Object.keys(NL.XCVR).every(k => W.get('xcvr-' + k.toLowerCase())), 'jeder Transceiver hat einen Artikel');
ok(Object.keys(NL.CARDS).every(k => W.get('card-' + k.toLowerCase())), 'jede Karte hat einen Artikel');
ok(all.every(a => a.title && a.short && a.body.length > 40), 'Titel, Kurztext und Inhalt vorhanden');
ok(W.search('vlan')[0].id === 'vlan', 'Suche: "vlan" -> VLAN zuerst');
ok(W.search('dac').some(a => a.id === 'kabel-dac'), 'Suche: DAC');
ok(W.search('sfp-10g-sr').some(a => a.id === 'xcvr-sfp-10g-sr'), 'Suche: Transceiver-Name');
ok(W.search('zoning wwpn').length > 0, 'Suche: mehrere Woerter');
ok(W.search('qqqqzzzz').length === 0, 'Suche: kein Treffer');
ok(!/\[\[/.test(W.links(W.get('kabel-uebersicht').body)), 'links() loest alle [[...]] auf');
process.exit(bad ? 1 : 0);
